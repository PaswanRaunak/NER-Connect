class ArchDiagram(Flowable):
    """Layered system architecture. Pale fills, adjacent-layer connectors."""
    W = 480
    H = 300

    def wrap(self, availW, availH):
        return self.W, self.H

    def _box(self, c, x, y, w, h, title, sub, fill, border):
        c.setFillColor(fill)
        c.setStrokeColor(border)
        c.setLineWidth(0.9)
        c.rect(x, y, w, h, stroke=1, fill=1)
        c.setFillColor(TEXT_PRIMARY)
        c.setFont("Times New Roman-Bold", 8.6)
        c.drawCentredString(x + w / 2, y + h / 2 + 3, title)
        c.setFillColor(TEXT_MUTED)
        c.setFont("Times New Roman", 7.2)
        c.drawCentredString(x + w / 2, y + h / 2 - 8, sub)

    def _label(self, c, x, y, text):
        c.setFillColor(TEXT_MUTED)
        c.setFont("Times New Roman-Bold", 7)
        c.drawString(x, y, text)

    def _arrow(self, c, x1, y1, x2, y2, dashed=False):
        c.setStrokeColor(ACCENT_SOFT)
        c.setLineWidth(0.9)
        if dashed:
            c.setDash(3, 2)
        c.line(x1, y1, x2, y2)
        c.setDash()
        import math
        ang = math.atan2(y2 - y1, x2 - x1)
        for da in (0.4, -0.4):
            c.line(x2, y2, x2 - 7 * math.cos(ang - da), y2 - 7 * math.sin(ang - da))

    def draw(self):
        c = self.canv
        gx, gw = 14, 336
